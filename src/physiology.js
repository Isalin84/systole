export function lvet(hr) { return TIMING.lvetIntercept + TIMING.lvetSlope * hr; }
export function pep(hr) { return TIMING.pepIntercept + TIMING.pepSlope * hr; }
export function ivrt(hr) { return Math.max(35, TIMING.ivrtRest * Math.sqrt((60000 / hr) / (60000 / TIMING.hrRest))); }
export function pq(hr) { return TIMING.pq * Math.pow((60000 / hr) / (60000 / TIMING.hrRest), TIMING.pqExponent); }

